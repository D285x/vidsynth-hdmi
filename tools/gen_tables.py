#!/usr/bin/env python3
"""Generates rtl/sin_lut.sv and prints the DDS note increments used in audio_gen.sv."""
import math
from pathlib import Path

root = Path(__file__).resolve().parent.parent
lines = ["// Generated by tools/gen_tables.py: 256-entry sine ROM, y = round(127.5 + 127.5 sin(2 pi a / 256))",
         "`default_nettype none", "module sin_lut (", "    input  wire logic [7:0] a,",
         "    output logic      [7:0] y", ");", "    always_comb begin", "        unique case (a)"]
for i in range(256):
    v = max(0, min(255, int(round(127.5 + 127.5 * math.sin(2 * math.pi * i / 256)))))
    lines.append(f"            8'd{i}: y = 8'd{v};")
lines += ["        endcase", "    end", "endmodule", "`default_nettype wire", ""]
(root / "rtl" / "sin_lut.sv").write_text("\n".join(lines))

notes = [("C4", 261.63), ("D4", 293.66), ("E4", 329.63), ("G4", 392.00),
         ("A4", 440.00), ("C5", 523.25), ("D5", 587.33), ("E5", 659.25)]
for name, f in notes:
    print(f"{name}: left {round(f / 48000 * 2**24)}, right {round(1.5 * f / 48000 * 2**24)}")
